        #region execute Updates
        /// <summary>
        /// Builds a single command that updates every row in <paramref name="chunk"/> in one round trip:
        /// N concatenated parameterized "UPDATE t SET ... WHERE ...;" statements (the same SQL-text
        /// batching technique EF Core uses internally), each row's parameters suffixed by row index
        /// to avoid name collisions.
        /// </summary>
        /// <param name="chunk">The rows (with their key and changed values) to update in this batch.</param>
        /// <param name="transaction">Transaction to execute within.</param>
        private IDbCommand buildBatchedUpdateCommand(IReadOnlyList<KeyValuePair<T, List<KeyValuePair<string, object>>>> chunk, IDbTransaction transaction)
        {
            var cmd = this.database.CreateCommand();
            cmd.Transaction = transaction;
            var editableFields = this.getEditableFieldList();
            var statements = new List<string>();
            for (var rowIndex = 0; rowIndex < chunk.Count; rowIndex++)
            {
                var rowValues = chunk[rowIndex].Value;
                var setClauses = new List<string>();
                foreach (var field in editableFields)
                {
                    var originalParamName = this.getParameterName(field.Name);
                    var batchParamName = $"{originalParamName}_{rowIndex}";
                    setClauses.Add(String.Format("{0}{1}{2} = {3}",
                        this.database.DDLHelper.DelimitedIdentifierStart,
                        field.Name,
                        this.database.DDLHelper.DelimitedIdentifierEnd,
                        batchParamName));

                    var value = rowValues.First(kv => kv.Key == originalParamName).Value;
                    this.validateParameterValue(value);
                    var param = cmd.CreateParameter();
                    param.ParameterName = batchParamName;
                    param.DbType = field.DatabaseType;
                    param.Value = normalizeParameterValue(value);
                    cmd.Parameters.Add(param);
                }

                var whereClauses = new List<string>();
                for (var keyIndex = 0; keyIndex < this.KeyFields.Count; keyIndex++)
                {
                    var keyField = this.KeyFields[keyIndex];
                    var originalKeyParamName = this.getKeyFieldParameterName(keyField.Name);
                    var batchKeyParamName = $"{originalKeyParamName}_{rowIndex}";
                    whereClauses.Add($"{this.database.DDLHelper.SafeFormatField(keyField.Name)} = {batchKeyParamName}");

                    var value = rowValues.First(kv => kv.Key == originalKeyParamName).Value;
                    var param = cmd.CreateParameter();
                    param.ParameterName = batchKeyParamName;
                    param.Value = normalizeParameterValue(value);
                    cmd.Parameters.Add(param);
                }
                statements.Add($"UPDATE {Name} SET {String.Join(",", setClauses)} WHERE {String.Join(" AND ", whereClauses)}");
            }
            cmd.CommandText = String.Join(";", statements);
            return cmd;
        }

