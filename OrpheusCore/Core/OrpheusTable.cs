        /// <summary>
        /// Asynchronously saves all pending changes.
        /// </summary>
        public async Task SaveAsync(CancellationToken cancellationToken = default)
        {
            var transaction = await this.database.BeginTransactionAsync(cancellationToken);
            this.OnBeforeSave?.Invoke(this, new SaveEventArguments() { Transaction = transaction });
            try
            {
                await this.executeDeleteAsync(transaction, cancellationToken);
                await this.executeUpdateAsync(transaction, cancellationToken);
                await this.executeInsertAsync(transaction, cancellationToken);
                await this.database.CommitTransactionAsync(transaction, cancellationToken);
                this.OnAfterSave?.Invoke(this, new SaveEventArguments() { Transaction = transaction });
            }
            catch (Exception exception)
            {
                await this.database.RollbackTransactionAsync(transaction, cancellationToken);
                this.logger.LogError(ErrorCodes.ERR_SAVING_DATA, exception, ErrorDictionary.GetError(ErrorCodes.ERR_SAVING_DATA));
                throw;
            }
        }
