        #region execute Inserts
        /// <summary>
        /// Builds a single command that inserts every row in <paramref name="chunk"/> in one round trip:
        /// "INSERT INTO t (col1,col2) VALUES (@col1_0,@col2_0),(@col1_1,@col2_1),...".
        /// Only valid for tables with no DB-generated key fields — those still need a per-row
        /// key-retrieval round trip, handled separately (see hasAutoGeneratedKeys branch below).
        /// </summary>
        /// <param name="chunk">The rows to insert in this batch.</param>
        /// <param name="transaction">Transaction to execute within.</param>
        private IDbCommand buildBatchedInsertCommand(IReadOnlyList<KeyValuePair<T, List<KeyValuePair<string, object>>>> chunk, IDbTransaction transaction)
        {
            var cmd = this.database.CreateCommand();
            cmd.Transaction = transaction;
            var editableFields = this.getEditableFieldList();
            var columnList = String.Join(",", editableFields.Select(fld => String.Format("{0}{1}{2}",
                this.database.DDLHelper.DelimitedIdentifierStart,
                fld.Name,
                this.database.DDLHelper.DelimitedIdentifierEnd)));

            var rowValueLists = new List<string>();
            for (var rowIndex = 0; rowIndex < chunk.Count; rowIndex++)
            {
                var rowValues = chunk[rowIndex].Value;
                var placeholders = new List<string>();
                foreach (var field in editableFields)
                {
                    var originalParamName = this.getParameterName(field.Name);
                    var batchParamName = $"{originalParamName}_{rowIndex}";
                    placeholders.Add(batchParamName);

                    var value = rowValues.First(kv => kv.Key == originalParamName).Value;
                    this.validateParameterValue(value);
                    var param = cmd.CreateParameter();
                    param.ParameterName = batchParamName;
                    param.DbType = field.DatabaseType;
                    param.Value = normalizeParameterValue(value);
                    cmd.Parameters.Add(param);
                }
                rowValueLists.Add($"({String.Join(",", placeholders)})");
            }
            cmd.CommandText = $"INSERT INTO {Name} ({columnList}) VALUES {String.Join(",", rowValueLists)}";
            return cmd;
        }

        /// <summary>
        /// Applies a DB-generated key value (from a batched insert) back onto a record, converting
        /// to the property's type since providers don't always return the exact CLR type the model
        /// property is declared as (e.g. MySQL's LAST_INSERT_ID() is a long; the key property may be int).
        /// </summary>
        private void applyGeneratedKey(T record, string keyFieldName, object value)
        {
            if (value == null || value == DBNull.Value)
                return;
            var propInfo = this.modelHelper.ModelProperties.FirstOrDefault(p => this.modelHelper.GetFieldNameForProperty(p) == keyFieldName);
            if (propInfo == null)
                return;
            var targetType = Nullable.GetUnderlyingType(propInfo.PropertyType) ?? propInfo.PropertyType;
            var convertedValue = targetType.IsInstanceOfType(value) ? value : Convert.ChangeType(value, targetType);
            propInfo.SetValue(record, convertedValue);
        }

        /// <summary>
        /// Builds, for a chunk of queued inserts, the column list and per-row raw values (in
        /// column order) needed by <see cref="IOrpheusDDLHelper.ExecuteBatchedInsertWithKeyRetrieval"/>.
        /// Only a single DB-generated key column is supported (the common case — one identity/serial
        /// primary key); composite DB-generated keys are not.
        /// </summary>
        private (List<string> columns, List<List<object>> rows) buildBatchedInsertWithKeyRetrievalInputs(IReadOnlyList<KeyValuePair<T, List<KeyValuePair<string, object>>>> chunk)
        {
            var editableFields = this.getEditableFieldList();
            var columns = editableFields.Select(f => f.Name).ToList();
            var rows = new List<List<object>>();
            foreach (var record in chunk)
            {
                var rowValues = new List<object>();
                foreach (var field in editableFields)
                {
                    var paramName = this.getParameterName(field.Name);
                    var value = record.Value.First(kv => kv.Key == paramName).Value;
                    this.validateParameterValue(value);
                    rowValues.Add(value);
                }
                rows.Add(rowValues);
            }
            return (columns, rows);
        }

        /// <summary>
        /// Executes inserts. Tables without DB-generated keys are batched into <see cref="BatchSize"/>-row
        /// round trips. Tables with a DB-generated key are also batched into <see cref="BatchSize"/>-row
        /// round trips, using the engine-specific key-retrieval strategy on <see cref="IOrpheusDDLHelper"/>
        /// (only a single DB-generated key column is supported).
        /// </summary>
        protected void executeInsert(IDbTransaction transaction)
        {
            var records = this.insertCommandValues.ToList();
            if (this.hasAutoGeneratedKeys)
            {
                var dbGeneratedKeyField = this.KeyFields.First(kf => kf.IsDBGenerated);
                foreach (var chunk in records.Chunk(this.BatchSize))
                {
                    var (columns, rows) = this.buildBatchedInsertWithKeyRetrievalInputs(chunk);
                    List<object> generatedKeys;
                    try
                    {
                        generatedKeys = this.database.DDLHelper.ExecuteBatchedInsertWithKeyRetrieval(Name, columns, dbGeneratedKeyField.Name, rows, transaction);
                    }
                    catch (Exception e)
                    {
                        this.logger.LogError(ErrorCodes.ERR_INSERTING_DATA, e, ErrorDictionary.GetError(ErrorCodes.ERR_INSERTING_DATA));
                        throw;
                    }
                    for (var i = 0; i < chunk.Length; i++)
                        this.applyGeneratedKey(chunk[i].Key, dbGeneratedKeyField.Name, generatedKeys[i]);
                }
            }
            else
            {
                foreach (var chunk in records.Chunk(this.BatchSize))
                {
                    using var cmd = this.buildBatchedInsertCommand(chunk, transaction);
                    try
                    {
                        cmd.ExecuteNonQuery();
                    }
                    catch (Exception e)
                    {
                        this.logger.LogError(ErrorCodes.ERR_INSERTING_DATA, e, $"{ErrorDictionary.GetError(ErrorCodes.ERR_INSERTING_DATA)} | {cmd.CommandText}");
                        throw;
                    }
                }
            }
            this.insertCommandValues.Clear();
        }

        /// <summary>
        /// Asynchronously executes inserts. See <see cref="executeInsert"/> for the batching rules.
        /// </summary>
        protected async Task executeInsertAsync(IDbTransaction transaction, CancellationToken cancellationToken = default)
        {
            var records = this.insertCommandValues.ToList();
            if (this.hasAutoGeneratedKeys)
            {
                var dbGeneratedKeyField = this.KeyFields.First(kf => kf.IsDBGenerated);
                foreach (var chunk in records.Chunk(this.BatchSize))
                {
                    var (columns, rows) = this.buildBatchedInsertWithKeyRetrievalInputs(chunk);
                    List<object> generatedKeys;
                    try
                    {
                        generatedKeys = await this.database.DDLHelper.ExecuteBatchedInsertWithKeyRetrievalAsync(Name, columns, dbGeneratedKeyField.Name, rows, transaction, cancellationToken);
                    }
                    catch (Exception e)
                    {
                        this.logger.LogError(ErrorCodes.ERR_INSERTING_DATA, e, ErrorDictionary.GetError(ErrorCodes.ERR_INSERTING_DATA));
                        throw;
                    }
                    for (var i = 0; i < chunk.Length; i++)
                        this.applyGeneratedKey(chunk[i].Key, dbGeneratedKeyField.Name, generatedKeys[i]);
                }
            }
            else
            {
                foreach (var chunk in records.Chunk(this.BatchSize))
                {
                    using var cmd = this.buildBatchedInsertCommand(chunk, transaction);
                    try
                    {
                        await ((DbCommand)cmd).ExecuteNonQueryAsync(cancellationToken);
                    }
                    catch (Exception e)
                    {
                        this.logger.LogError(ErrorCodes.ERR_INSERTING_DATA, e, $"{ErrorDictionary.GetError(ErrorCodes.ERR_INSERTING_DATA)} | {cmd.CommandText}");
                        throw;
                    }
                }
            }
            this.insertCommandValues.Clear();
        }
