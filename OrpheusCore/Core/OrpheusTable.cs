        private string getMasterKeyFieldNameFromForeignKey(KeyValuePair<string, object> masterKeyValue)
        {
            return this.getMasterKeyFieldNameFromForeignKey(masterKeyValue.Key);
        }

        private void validateParameterValue(object value)
        {
            // Null check must come first � calling .GetType() on null throws NullReferenceException.
            if (value == null || value == DBNull.Value)
                return;
            // DateTime values must not be DateTime.MinValue (used as sentinel for unset dates).
            if (value is DateTime dt && dt == DateTime.MinValue)
                throw new ArgumentNullException(nameof(value), "A date time property must have a value.");
        }

        /// <summary>
        /// Converts a field value into something safe to box as an ADO.NET parameter value.
        /// Null becomes DBNull.Value. Enum values are converted to their underlying integral type -
        /// SqlClient/MySqlConnector implicitly accept a boxed enum for an integer column, but Npgsql
        /// does not: it throws InvalidCastException unless the value's runtime type already matches
        /// the target column's mapped .NET type. Any non-UTC DateTime.Kind is relabeled to Utc -
        /// Npgsql's default (non-legacy) DbType.DateTime mapping resolves to "timestamp with time
        /// zone" regardless of the actual column, and rejects both Local and Unspecified outright;
        /// SqlClient/MySqlConnector never cared about Kind in the first place, only the wall-clock
        /// value, so relabeling (not converting) the same numbers as UTC changes nothing for them.
        /// </summary>
        private static object normalizeParameterValue(object value)
        {
            if (value == null)
                return DBNull.Value;
            if (value.GetType().IsEnum)
                return Convert.ChangeType(value, Enum.GetUnderlyingType(value.GetType()));
            if (value is DateTime dt && dt.Kind != DateTimeKind.Utc)
                return DateTime.SpecifyKind(dt, DateTimeKind.Utc);
            return value;
        }


        /// <summary>
        /// Iterates through the model properties to find out primary, foreign keys.
        /// </summary>
        private void intializeModelProperties()
        {
            foreach (KeyValuePair<string, IPrimaryKey> pk in this.modelHelper.PrimaryKeys)
            {
                if (this.KeyFields.Where(kf => kf.Name.ToLower() == pk.Key.ToLower()).Count() == 0)
                {
                    var newKeyField = new OrpheusTableKeyField();
                    newKeyField.IsDBGenerated = pk.Value.IsDBGenerated;
                    newKeyField.IsAutoGenerated = pk.Value.IsAutoGenerated;
                    newKeyField.Name = pk.Key;

                    this.KeyFields.Add(newKeyField);
                }
            }

            foreach (KeyValuePair<string, IForeignKey> fk in this.modelHelper.ForeignKeys)
            {
                if (this.MasterTableKeyFields.Where(kf => kf.Name.ToLower() == fk.Key.ToLower()).Count() == 0)
                {
                    //foreign keys are not all master keys are not all  , but just the ones that belong to the master table.
                    if (this.MasterTable != null && this.MasterTable.Name.ToLower() == fk.Value.ReferenceTable.ToLower())
                    {
                        var newKeyField = new OrpheusTableKeyField();

                        newKeyField.Name = fk.Key;

                        this.MasterTableKeyFields.Add(newKeyField);
                    }
                }
            }
        }

        /// <summary>
        /// Loads table data.
        /// </summary>
        private void loadData(IDbCommand dbCommand = null)
        {
            if (dbCommand == null)
                dbCommand = this.loadCommand;
            IDataReader dataReader = null;
            try
            {
                dataReader = dbCommand.ExecuteReader();
                var fieldCount = dataReader.FieldCount;
                var fields = new List<int>();
                var properties = new List<PropertyInfo>();
                for (int i = 0; i <= fieldCount - 1; i++)
                {
                    var fldName = dataReader.GetName(i);
                    PropertyInfo propInfo = this.modelHelper.ModelProperties.FirstOrDefault(p => this.modelHelper.GetFieldNameForProperty(p) == fldName);
                    if (propInfo != null)
                    {
                        fields.Add(i);
                        properties.Add(propInfo);
                    }
                }
                while (dataReader.Read())
                {
                    T newInstance = Activator.CreateInstance<T>();
                    for (var i = 0; i <= fields.Count - 1; i++)
                    {
                        var value = dataReader.GetValue(fields[i]);
                        var property = properties[i];
                        value = value.GetType() == typeof(System.DBNull) ? null : value;
                        //special handling when the DBEngine does not support natively the Guid type and saves it
                        //as a string.
                        if (!this.database.DDLHelper.SupportsGuidType)
                        {
                            if (property.PropertyType == typeof(System.Guid) && value.GetType() == typeof(System.String))
                            {
                                value = Guid.Parse((string)value);
                            }

                        }
                        property.SetValue(newInstance, value);
                    }
                    data.Add(newInstance);
                }
            }
            catch (Exception e)
            {
                this.logger.LogError(ErrorCodes.ERR_LOADING_DATA, e, $"{ErrorDictionary.GetError(ErrorCodes.ERR_LOADING_DATA)} | {dbCommand.CommandText}");
                throw;
            }
            finally
            {
                if (dataReader != null)
                {
                    dataReader.Close();
                    dataReader.Dispose();
                }
            }
        }

        /// <summary>
        /// Asynchronously loads table data.
        /// </summary>
        private async Task loadDataAsync(IDbCommand dbCommand = null, CancellationToken cancellationToken = default)
        {
            if (dbCommand == null)
                dbCommand = this.loadCommand;
            DbDataReader dataReader = null;
            try
            {
                dataReader = await ((DbCommand)dbCommand).ExecuteReaderAsync(cancellationToken);
                var fieldCount = dataReader.FieldCount;
                var fields = new List<int>();
                var properties = new List<PropertyInfo>();
                for (int i = 0; i <= fieldCount - 1; i++)
                {
                    var fldName = dataReader.GetName(i);
                    PropertyInfo propInfo = this.modelHelper.ModelProperties.FirstOrDefault(p => this.modelHelper.GetFieldNameForProperty(p) == fldName);
                    if (propInfo != null)
                    {
                        fields.Add(i);
                        properties.Add(propInfo);
                    }
                }
                while (await dataReader.ReadAsync(cancellationToken))
                {
                    T newInstance = Activator.CreateInstance<T>();
                    for (var i = 0; i <= fields.Count - 1; i++)
                    {
                        var value = dataReader.GetValue(fields[i]);
                        var property = properties[i];
                        value = value.GetType() == typeof(System.DBNull) ? null : value;
                        //special handling when the DBEngine does not support natively the Guid type and saves it
                        //as a string.
                        if (!this.database.DDLHelper.SupportsGuidType)
                        {
                            if (property.PropertyType == typeof(System.Guid) && value.GetType() == typeof(System.String))
                            {
                                value = Guid.Parse((string)value);
                            }

                        }
                        property.SetValue(newInstance, value);
                    }
                    data.Add(newInstance);
                }
            }
            catch (Exception e)
            {
                this.logger.LogError(ErrorCodes.ERR_LOADING_DATA, e, $"{ErrorDictionary.GetError(ErrorCodes.ERR_LOADING_DATA)} | {dbCommand.CommandText}");
                throw;
            }
            finally
            {
                if (dataReader != null)
                {
                    await dataReader.DisposeAsync();
                }
            }
        }

