        /// Maximum number of rows batched into a single round trip when executing
        /// queued inserts/updates/deletes. Default: 100 — empirically, larger batches
        /// (e.g. 250) trade fewer round trips for more expensive per-batch statement
        /// compilation, which can net out worse, especially for updates (each row still
        /// needs its own full UPDATE statement, unlike insert's compact multi-row VALUES).
        /// Tune per workload/engine if needed.
