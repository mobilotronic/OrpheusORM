        /// <summary>
        /// Asynchronously loads data using key-value pair filter.
        /// </summary>
        public async Task LoadAsync(List<object> keyValues, CancellationToken cancellationToken = default)
        {
            if (this.KeyFields.Count == 1)
            {
                await this.loadAsync(new Dictionary<string, List<object>>() {
                    {
                        this.KeyFields.First().Name,
                        keyValues
                    }
                }, LogicalOperator.loOR, true, cancellationToken);
            }
            else
                throw new InvalidExpressionException("When an Orpheus table has more than one key fields, you cannot use the 'simple' load. Values for each field much be determined.");
        }

