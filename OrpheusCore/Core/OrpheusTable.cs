        #region execute Deletes
        /// <summary>
        /// Builds a single command that deletes every row in <paramref name="chunk"/> in one round trip:
        /// "DELETE FROM t WHERE (key1=@k1_0 AND key2=@k2_0) OR (key1=@k1_1 AND key2=@k2_1) OR ..."
        /// (single-key tables omit the parentheses since there's only one condition per row).
        /// </summary>
        /// <param name="chunk">The rows (with their key values) to delete in this batch.</param>
        /// <param name="transaction">Transaction to execute within.</param>
        private IDbCommand buildBatchedDeleteCommand(IReadOnlyList<KeyValuePair<T, List<KeyValuePair<string, object>>>> chunk, IDbTransaction transaction)
        {
            var cmd = this.database.CreateCommand();
            cmd.Transaction = transaction;
            var rowClauses = new List<string>();
            for (var rowIndex = 0; rowIndex < chunk.Count; rowIndex++)
            {
                var rowValues = chunk[rowIndex].Value;
                var conditions = new List<string>();
                for (var keyIndex = 0; keyIndex < this.KeyFields.Count; keyIndex++)
                {
                    var keyField = this.KeyFields[keyIndex];
                    var originalParamName = this.getKeyFieldParameterName(keyField.Name);
                    var batchParamName = $"{originalParamName}_{rowIndex}";
                    conditions.Add(String.Format("{0}{1}{2} = {3}",
                        this.database.DDLHelper.DelimitedIdentifierStart,
                        keyField.Name,
                        this.database.DDLHelper.DelimitedIdentifierEnd,
                        batchParamName));

                    var value = rowValues.First(kv => kv.Key == originalParamName).Value;
                    var param = cmd.CreateParameter();
                    param.ParameterName = batchParamName;
                    param.Value = normalizeParameterValue(value);
                    cmd.Parameters.Add(param);
                }
                rowClauses.Add(conditions.Count > 1 ? $"({String.Join(" AND ", conditions)})" : conditions[0]);
            }
            cmd.CommandText = $"DELETE FROM {Name} WHERE {String.Join(" OR ", rowClauses)}";
            return cmd;
        }

        /// <summary>
        /// Executes deletes, chunked into batches of <see cref="BatchSize"/> rows per round trip.
        /// </summary>
        protected void executeDelete(IDbTransaction transaction)
        {
            var records = this.deleteCommandValues.ToList();
            foreach (var chunk in records.Chunk(this.BatchSize))
            {
                using var cmd = this.buildBatchedDeleteCommand(chunk, transaction);
                try
                {
                    cmd.ExecuteNonQuery();
                }
                catch (Exception e)
                {
                    this.logger.LogError(ErrorCodes.ERR_DELETING_DATA, e, $"{ErrorDictionary.GetError(ErrorCodes.ERR_DELETING_DATA)} | {cmd.CommandText}");
                    throw;
                }
            }
            this.deleteCommandValues.Clear();
        }

        /// <summary>
        /// Asynchronously executes deletes, chunked into batches of <see cref="BatchSize"/> rows per round trip.
        /// </summary>
        protected async Task executeDeleteAsync(IDbTransaction transaction, CancellationToken cancellationToken = default)
        {
            var records = this.deleteCommandValues.ToList();
            foreach (var chunk in records.Chunk(this.BatchSize))
            {
                using var cmd = this.buildBatchedDeleteCommand(chunk, transaction);
                try
                {
                    await ((DbCommand)cmd).ExecuteNonQueryAsync(cancellationToken);
                }
                catch (Exception e)
                {
                    this.logger.LogError(ErrorCodes.ERR_DELETING_DATA, e, $"{ErrorDictionary.GetError(ErrorCodes.ERR_DELETING_DATA)} | {cmd.CommandText}");
                    throw;
                }
            }
            this.deleteCommandValues.Clear();
        }
